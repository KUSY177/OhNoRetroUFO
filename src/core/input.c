#include "input.h"
#include "raylib.h"

// ------------------------------------------------------------
// Инициализация
// ------------------------------------------------------------
void Input_Init(void) {
    // Ничего не нужно — Raylib сам инициализирует ввод
}

// ------------------------------------------------------------
// Обновление (Raylib делает всё сам)
// ------------------------------------------------------------
void Input_Update(void) {
    // Пусто — Raylib сам обновляет состояние клавиш/мыши
}

// ------------------------------------------------------------
// Выход
// ------------------------------------------------------------
bool Input_ShouldQuit(void) {
    return WindowShouldClose();
}

// ------------------------------------------------------------
// Клавиша удерживается
// ------------------------------------------------------------
bool Input_IsKeyDown(int key) {
    return IsKeyDown(key);
}

// ------------------------------------------------------------
// Клавиша нажата в этом кадре
// ------------------------------------------------------------
bool Input_IsKeyPressed(int key) {
    return IsKeyPressed(key);
}

// ------------------------------------------------------------
// Кнопка мыши нажата в этом кадре
// ------------------------------------------------------------
bool Input_IsMousePressed(int button) {
    return IsMouseButtonPressed(button);
}
